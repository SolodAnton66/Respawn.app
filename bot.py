import os
import random
import telebot
from dotenv import load_dotenv

# Завантажуємо змінні оточення з файлу .env
load_dotenv()

# Отримуємо токен бота через змінну оточення (без зберігання у коді)
TOKEN = os.getenv("BOT_TOKEN")

# Створюємо екземпляр бота
bot = telebot.TeleBot(TOKEN)

# Вбудований список із 5 підказок для вечірніх ігрових та кіносесій
EVENING_IDEAS = [
    "🎬 Кіносеанс: Перегляд фіналу кіберспортивного турніру (наприклад, Major з CS2 або The International) під піцу.",
    "🎮 Кооперативна катка: Проходження сюжетної гри на двох або вчотирьох (It Takes Two, Lethal Company або Helldivers 2).",
    "🍿 Документалка + розігрів: Перегляд фільму «Free to Play» або «True Sight», а потім 2–3 рейтингові матчі.",
    "🏆 Міні-турнір серед своїх: Швидкі матчі 1 на 1 або 2 на 2 на виліт у улюбленому шутері чи файтингу.",
    "📽️ Фантастичний кіновечір: Перегляд фільму про віртуальну реальність або ігри («Першому гравцю приготуватися» або «Трон: Спадок»)."
]

# Обробник команди /start — привітання та опис бота
@bot.message_handler(commands=["start"])
def send_welcome(message):
    welcome_text = (
        "Вітаю у боті «Плейлист та Катки»! 🎮🎬\n\n"
        "Я — ваш довідник-підказка для вечірніх сесій. Допоможу компанії друзів "
        "швидко обрати формат спільного вечора (гра чи кіно), щоб не витрачати час на довгі суперечки.\n\n"
        "Тисни /pick, щоб отримати випадкову ідею на сьогодні, або /help для довідки."
    )
    bot.reply_to(message, welcome_text)

# Обробник команди /help — список команд та довідка
@bot.message_handler(commands=["help"])
def send_help(message):
    help_text = (
        "📋 Доступні команди:\n"
        "/start — привітання та короткий опис бота\n"
        "/help — показати цей список команд і довідку\n"
        "/pick — отримати випадкову підказку для вечірньої катки чи кіноперегляду"
    )
    bot.reply_to(message, help_text)

# Обробник команди /pick — випадковий вибір із 5 варіантів
@bot.message_handler(commands=["pick"])
def pick_activity(message):
    # Обираємо один випадковий пункт зі списку
    chosen_idea = random.choice(EVENING_IDEAS)
    bot.reply_to(message, f"Твій формат на цей вечір:\n\n{chosen_idea}")

# Запуск нескінченного циклу роботи бота
if __name__ == "__main__":
    print("Бот «Плейлист та Катки» запущений...")
    bot.infinity_polling()
